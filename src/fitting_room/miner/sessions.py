"""Read agent session histories into one common shape (spec: session-mining; design D7).

Readers are read-only: JSONL files are opened for reading and SQLite is opened with
``mode=ro``. Each reader yields ``Session`` objects whose ``messages`` hold only what
matters for mining: human messages (injected context filtered out), assistant text,
and tool calls with a short argument summary.
"""

from __future__ import annotations

import json
import sqlite3
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

HUMAN, ASSISTANT, TOOL = "human", "assistant", "tool"

# Text blocks harnesses inject as "user" messages that the human did not type.
_INJECTED_PREFIXES = (
    "<environment_context>",
    "<external_codex_apps_open_page>",
    "<send_user_message_question_reply>",
    "<user_instructions>",
    "<system-reminder>",
    "<command-name>",
    "<command-message>",
    "<local-command-stdout>",
    "<local-command-caveat>",
    "<task-notification>",
    "# AGENTS.md instructions for",
    "Caveat: The messages below were generated by the user while running local commands",
)


def is_injected(text: str) -> bool:
    t = text.lstrip()
    return not t or t.startswith(_INJECTED_PREFIXES)


@dataclass
class Message:
    role: str  # human | assistant | tool
    text: str = ""
    ts: str | None = None  # ISO 8601
    ref: str = ""  # JSONL line number or DB row id, for citing evidence
    tool_name: str | None = None
    tool_args: str = ""  # short summary: command, file path, ...


@dataclass
class Session:
    source: str  # codex | claude | hermes | omp
    session_id: str
    path: str
    cwd: str | None
    branch: str | None = None
    commit: str | None = None
    started: str | None = None
    is_subagent: bool = False
    model: str | None = None
    messages: list[Message] = field(default_factory=list)

    @property
    def human_messages(self) -> list[Message]:
        return [m for m in self.messages if m.role == HUMAN]


def _iso_from_epoch(value) -> str | None:
    if value is None:
        return None
    return datetime.fromtimestamp(float(value), tz=UTC).isoformat().replace("+00:00", "Z")


def _summarize_args(args) -> str:
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except (json.JSONDecodeError, ValueError):
            return args[:300]
    if isinstance(args, dict):
        for key in ("command", "cmd", "file_path", "path", "pattern", "query", "input"):
            if key in args and args[key]:
                val = args[key]
                return (" ".join(val) if isinstance(val, list) else str(val))[:300]
        return json.dumps(args)[:300]
    return str(args)[:300]


def _read_jsonl(path: Path) -> Iterator[tuple[int, dict]]:
    with path.open(encoding="utf-8", errors="replace") as fh:
        for n, line in enumerate(fh, start=1):
            try:
                yield n, json.loads(line)
            except json.JSONDecodeError:
                continue


# ---------------------------------------------------------------------------- Codex
def read_codex(path: Path) -> Session | None:
    sess: Session | None = None
    for n, d in _read_jsonl(path):
        t, p = d.get("type"), d.get("payload") or {}
        if t == "session_meta":
            git = p.get("git") or {}
            src = json.dumps(p.get("source") or "")
            sess = Session(
                source="codex",
                session_id=p.get("id", path.stem),
                path=str(path),
                cwd=p.get("cwd"),
                branch=git.get("branch"),
                commit=git.get("commit_hash"),
                started=p.get("timestamp") or d.get("timestamp"),
                is_subagent=p.get("thread_source") == "subagent" or "subagent" in src,
            )
            continue
        if sess is None or t != "response_item" or not isinstance(p, dict):
            if sess and t == "turn_context" and isinstance(p, dict) and p.get("model"):
                sess.model = sess.model or p.get("model")
            continue
        ts, ref = d.get("timestamp"), f"L{n}"
        ptype = p.get("type")
        if ptype == "message" and p.get("role") == "user":
            for c in p.get("content") or []:
                text = c.get("text", "") if isinstance(c, dict) else ""
                if not is_injected(text):
                    sess.messages.append(Message(HUMAN, text, ts, ref))
        elif ptype == "message" and p.get("role") == "assistant":
            text = " ".join(
                c.get("text", "") for c in p.get("content") or [] if isinstance(c, dict)
            ).strip()
            if text:
                sess.messages.append(Message(ASSISTANT, text, ts, ref))
        elif ptype in ("function_call", "custom_tool_call", "local_shell_call"):
            args = p.get("arguments") or p.get("input") or p.get("action") or ""
            sess.messages.append(
                Message(TOOL, "", ts, ref, p.get("name") or ptype, _summarize_args(args))
            )
    return sess


# ---------------------------------------------------------------------------- Claude
def read_claude(path: Path) -> Session | None:
    sess = Session(source="claude", session_id=path.stem, path=str(path), cwd=None)
    sidechain_only = True
    for n, d in _read_jsonl(path):
        t = d.get("type")
        if t not in ("user", "assistant"):
            continue
        if not d.get("isSidechain"):
            sidechain_only = False
        if d.get("isSidechain") or d.get("isMeta"):
            continue
        sess.cwd = sess.cwd or d.get("cwd")
        sess.branch = sess.branch or d.get("gitBranch")
        sess.started = sess.started or d.get("timestamp")
        ts, ref = d.get("timestamp"), f"L{n}"
        content = (d.get("message") or {}).get("content")
        if t == "user":
            items = [{"type": "text", "text": content}] if isinstance(content, str) else content
            for it in items or []:
                if it.get("type") == "text" and not is_injected(it.get("text", "")):
                    sess.messages.append(Message(HUMAN, it["text"], ts, ref))
        else:
            sess.model = sess.model or (d.get("message") or {}).get("model")
            for it in content or []:
                if it.get("type") == "text" and it.get("text", "").strip():
                    sess.messages.append(Message(ASSISTANT, it["text"], ts, ref))
                elif it.get("type") == "tool_use":
                    sess.messages.append(
                        Message(TOOL, "", ts, ref, it.get("name"), _summarize_args(it.get("input")))
                    )
    if sess.started is None:
        return None
    sess.is_subagent = sidechain_only or "/subagents/" in str(path)
    return sess


# ---------------------------------------------------------------------------- Oh My Pi
def read_omp(path: Path) -> Session | None:
    sess: Session | None = None
    for n, d in _read_jsonl(path):
        t = d.get("type")
        if t == "session":
            sess = Session(
                source="omp",
                session_id=d.get("id", path.stem),
                path=str(path),
                cwd=d.get("cwd"),
                started=d.get("timestamp"),
                is_subagent=bool(d.get("parentSession") or d.get("parentId")),
            )
            continue
        if sess is None:
            continue
        if t == "model_change" and not sess.model:
            sess.model = d.get("model")
        if t != "message":
            continue
        m, ts, ref = d.get("message") or {}, d.get("timestamp"), f"L{n}"
        role = m.get("role")
        if role == "user":
            for it in m.get("content") or []:
                if it.get("type") == "text" and not is_injected(it.get("text", "")):
                    sess.messages.append(Message(HUMAN, it["text"], ts, ref))
        elif role == "assistant":
            for it in m.get("content") or []:
                if it.get("type") == "text" and it.get("text", "").strip():
                    sess.messages.append(Message(ASSISTANT, it["text"], ts, ref))
                elif it.get("type") == "toolCall":
                    sess.messages.append(
                        Message(
                            TOOL, "", ts, ref, it.get("name"), _summarize_args(it.get("arguments"))
                        )
                    )
    return sess


# ---------------------------------------------------------------------------- Hermes
def read_hermes(db_path: Path) -> Iterator[Session]:
    """Yield sessions from Hermes's SQLite store, opened read-only."""
    uri = f"file:{db_path}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        con.row_factory = sqlite3.Row
        rows = con.execute(
            "SELECT id, cwd, git_branch, git_repo_root, parent_session_id, started_at, model "
            "FROM sessions ORDER BY started_at"
        ).fetchall()
        for r in rows:
            sess = Session(
                source="hermes",
                session_id=r["id"],
                path=f"{db_path}#sessions/{r['id']}",
                cwd=r["cwd"] or r["git_repo_root"],
                branch=r["git_branch"],
                started=_iso_from_epoch(r["started_at"]),
                is_subagent=r["parent_session_id"] is not None,
                model=r["model"],
            )
            for m in con.execute(
                "SELECT id, role, content, tool_calls, timestamp FROM messages "
                "WHERE session_id = ? ORDER BY timestamp, id",
                (r["id"],),
            ):
                ts, ref = _iso_from_epoch(m["timestamp"]), f"messages/{m['id']}"
                text = m["content"] if isinstance(m["content"], str) else ""
                if m["role"] == "user" and not is_injected(text):
                    sess.messages.append(Message(HUMAN, text, ts, ref))
                elif m["role"] == "assistant":
                    if text.strip():
                        sess.messages.append(Message(ASSISTANT, text, ts, ref))
                    for call in json.loads(m["tool_calls"] or "[]") or []:
                        fn = call.get("function") or call
                        sess.messages.append(
                            Message(
                                TOOL,
                                "",
                                ts,
                                ref,
                                fn.get("name"),
                                _summarize_args(fn.get("arguments")),
                            )
                        )
            yield sess
    finally:
        con.close()


# ---------------------------------------------------------------------------- discovery
DEFAULT_SOURCES = {
    "codex": Path("~/.codex/sessions"),
    "claude": Path("~/.claude/projects"),
    "hermes": Path("~/.hermes/state.db"),
    "omp": Path("~/.omp/agent/sessions"),
}


def iter_sessions(sources: dict[str, Path] | None = None) -> Iterator[Session]:
    """Yield sessions from every configured source that exists."""
    for name, base in (sources or DEFAULT_SOURCES).items():
        base = base.expanduser()
        if not base.exists():
            continue
        if name == "codex":
            for f in sorted(base.rglob("*.jsonl")):
                if s := read_codex(f):
                    yield s
        elif name == "claude":
            for f in sorted(base.glob("*/*.jsonl")):  # top level only: skips subagents/
                if s := read_claude(f):
                    yield s
        elif name == "omp":
            for f in sorted(base.glob("*/*.jsonl")):
                if s := read_omp(f):
                    yield s
        elif name == "hermes":
            yield from read_hermes(base)
