"""Model providers a run configuration can name (design D5).

Benchmarked models are GLM (z.ai) and local models. No real key ever enters a sandbox:

- ``zai``: the agent gets a placeholder key. The host's Agent Vault (a Windows MITM
  proxy) intercepts ``api.z.ai`` and substitutes the real key in-flight. Containers
  reach it through Docker Desktop's DNS forwarding; they only need to trust Agent
  Vault's *public* root CA, which a generated Compose overlay mounts.
- ``local``: a serving profile on the host (``fr serve up``) reached through
  ``host.docker.internal``; llama.cpp ignores the key, so a placeholder works.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path

AGENT_VAULT_CA = Path("/mnt/c/ProgramData/AgentVault/agent-vault-ca.pem")
# NixOS's system bundle already includes the Agent Vault CA (security.pki config).
SYSTEM_CA_BUNDLE = Path("/etc/ssl/certs/ca-bundle.crt")
CERTS_MOUNT = "/opt/fr-certs"


@dataclass(frozen=True)
class Provider:
    name: str
    anthropic_base_url: str | None = None
    openai_base_url: str | None = None
    placeholder_key: str = "placeholder"
    needs_agent_vault_ca: bool = False
    allowed_hosts: tuple[str, ...] = ()


PROVIDERS: dict[str, Provider] = {
    "zai": Provider(
        name="zai",
        anthropic_base_url="https://api.z.ai/api/anthropic",
        placeholder_key="av-managed-key",
        needs_agent_vault_ca=True,
        allowed_hosts=("api.z.ai",),
    ),
    "local": Provider(
        name="local",
        openai_base_url="http://host.docker.internal:18080/v1",
        placeholder_key="placeholder",
        allowed_hosts=("host.docker.internal",),
    ),
}


def stage_certs(work_dir: Path) -> Path:
    """Copy the public Agent Vault CA and a combined trust bundle into work/certs."""
    if not AGENT_VAULT_CA.is_file():
        raise FileNotFoundError(f"Agent Vault CA not found at {AGENT_VAULT_CA}")
    certs = work_dir / "certs"
    certs.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(AGENT_VAULT_CA, certs / "agent-vault-ca.pem")
    bundle = SYSTEM_CA_BUNDLE.read_text() if SYSTEM_CA_BUNDLE.is_file() else ""
    ca = AGENT_VAULT_CA.read_text()
    if ca.strip() not in bundle:
        bundle = bundle.rstrip() + "\n" + ca
    (certs / "ca-bundle.crt").write_text(bundle)
    for f in certs.iterdir():
        f.chmod(0o644)
    return certs.resolve()


def write_ca_overlay(certs_dir: Path, dest: Path) -> Path:
    """Compose overlay that mounts the certs read-only and points TLS clients at them."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        "# Generated by fitting-room: trust the host's Agent Vault root CA (public cert only).\n"
        "services:\n"
        "  main:\n"
        "    volumes:\n"
        f"      - {certs_dir}:{CERTS_MOUNT}:ro\n"
        "    environment:\n"
        f"      NODE_EXTRA_CA_CERTS: {CERTS_MOUNT}/agent-vault-ca.pem\n"
        f"      SSL_CERT_FILE: {CERTS_MOUNT}/ca-bundle.crt\n"
        f"      REQUESTS_CA_BUNDLE: {CERTS_MOUNT}/ca-bundle.crt\n"
        f"      CURL_CA_BUNDLE: {CERTS_MOUNT}/ca-bundle.crt\n"
    )
    return dest
